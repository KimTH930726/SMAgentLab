"""한국어 조사/어미 규칙 기반 제거 — RDB(policy_param) 키워드 검색의 형태소 공백을 메운다.

배경: PostgreSQL `to_tsvector('simple', ...)`엔 한국어 형태소 분석이 없어 "담을"/"담기"처럼
같은 어간이라도 조사·어미가 다르면 전혀 다른 lexeme으로 취급돼 매칭이 실패한다(2026-09-10
Track2 재검증에서 발견 — RDB 자기 전문 분야인 param 질의에서조차 벡터(47.8%)가 RDB(26.1%)를
앞섬). mecab-ko/Kiwi 같은 진짜 형태소 분석기는 별도 프로세스·사전 유지보수 부담이 있어,
이 프로젝트 규모(policy_param 389건)에선 실측으로 먼저 검증한 저비용 규칙 기반 제거를
우선 적용한다 — "규칙기반 조사제거하고 정확도를 한번 비교해보자"는 요청에 따른 실험
(`backend/scripts/bench_suffix_stripping.py`)에서 개선이 확인됐다:
- RDB(param) 채널 단독: hit@10 34.8%→73.9%
- 하이브리드(RDB+벡터) 전체: hit@10 75.3%→79.8%(+4.5pp), navigation +12.5pp

**이 파일의 `_SUFFIXES`는 `init/06-policy-strip-ko.sql`의 SQL 함수 `policy_strip_ko_word()`와
동작이 같아야 한다** — 하나는 오프라인 실험/재사용 스크립트용(이 파일), 다른 하나는
`service/policy/search.py`가 실제 쿼리에서 쓰는 프로덕션 경로(SQL 함수, DB 안에서
policy_param/policy_item 원문 컬럼에 바로 적용돼 저장 컬럼 추가 없이 실시간 변환)다.
SQL 쪽은 "일치하는 접미사 중 가장 긴 것" 방식이라 배열 순서에 무관하게 이 목록과 동일한
집합이면 항상 같은 결과를 낸다(동일 위치에서 같은 길이의 접미사는 하나만 매칭 가능하므로
"정렬 후 첫 매치"와 "가장 긴 매치"는 항상 같은 답을 준다).
"""
from __future__ import annotations

# 조사·어미(생산적/규칙적인 것 위주) — 길이 긴 것부터 그리디 매칭. 불규칙 활용(듣다→들어류)은
# 못 잡음, 실험의 한계로 결과 해석 시 감안. 최소 잔여 어간 2글자 보장(과도한 절단 방지).
_SUFFIXES = sorted([
    "까지는", "에서는", "으로는", "한테는", "에게서", "으로써",
    "이라도", "에서", "으로", "부터", "한테", "에게", "까지", "처럼", "보다",
    "이랑", "랑", "하고", "이며",
    "습니다", "입니다", "겠습니다", "습니까",
    "으며", "면서", "니까", "아서", "어서", "인데", "은데",
    "어요", "아요", "네요", "군요",
    "았고", "었고",
    "은", "는", "이", "가", "을", "를", "의", "도", "만", "에", "로", "와", "과",
    "고", "게", "지", "며", "니", "자", "다", "죠", "기", "아", "어",
], key=len, reverse=True)


def strip_suffix(word: str) -> str:
    """단어 하나에서 가장 긴 매칭 접미사 1개를 제거. 남는 어간이 2글자 미만이면 절단하지 않는다."""
    for suf in _SUFFIXES:
        if word.endswith(suf) and len(word) - len(suf) >= 2:
            return word[: -len(suf)]
    return word


def strip_text(text: str) -> str:
    """공백 단위로 쪼개 단어마다 조사/어미를 제거하고 다시 합친다."""
    return " ".join(strip_suffix(w) for w in text.split())
