"""질문 유형 판별(규칙) — 유형마다 문맥 범위·답 구조·리랭커 사용을 달리하기 위한 값싼 신호.

LLM 분류기 대신 규칙인 이유: 판별이 틀려도 "평소대로 답"으로 떨어지게 설계해(해가 없는 방향) 정밀도만 지키면 된다.
패턴은 인자로 바꿀 수 있다(다른 도메인·언어). 기본값은 한국어, OpsLens 골든 88 실측:
- 탐색형(목록 전체): 정밀도 96%·재현율 100% ("한 번에"는 수량 질문과 충돌해 제외). 10/21 목록 말투 확장 후 골든 v0+v1 530문항:
  목록형 42/42, 다른 유형 오탐 3/488(전부 확장 전부터 있던 "전체" 단어 오탐)
- 조건 한정("X에만/때만/전용"): 조건형 18/18 · 다른 유형 1/70 — 골든 질문이 한 틀이라 실제 질문 재현율은 운영에서 확인 필요
"""
from __future__ import annotations

import re
from typing import Pattern

# 둘째 줄(2026-10-21) — "전체·모든" 없이 묻는 목록 말투: "○○ 기준 정리해줘", "기준에는 뭐가 있어?", "어떤 운영 기준들이 있어?",
# "조건들 정리해줘", "결재기준 전반". OpsLens v0 골든 목록형 18문항 중 9문항이 첫 줄에 안 걸려 분류 목록 없이 답했다(목록형 정답 33%).
# "정리해?"(처분)·"권종은 뭐가 있어?"(한 정책 안의 값)는 안 걸리게 명령형·"기준/정책…+뭐가 있"으로 좁혔다 — 골든 530문항 새 오탐 0.
NAV_SIGNAL_RE: Pattern = re.compile(
    r"전체|모든|모두|리스트|목록|한눈에|다\s*(볼|보여|알려|확인)"
    r"|(기준|정책|규정|규칙|항목)\S{0,3}\s*정리해\s*(줘|주세요|주실|줄)|전반(?!적으로\s*(어때|어떻))"
    r"|(기준|정책|규정|규칙)\S{0,3}\s*(뭐가|뭐뭐|무엇이|어떤\s*(것|게|거)들?이?)\s*있"
    r"|어떤\s*[가-힣A-Za-z ]{0,10}(기준|정책|규정|규칙|항목)들이\s*있"
    r"|(기준|정책|규정|규칙|항목|조건)들\s*(을|를)?\s*(전체적으로\s*)?(정리|알려|보여|나열)")
# "만"은 앞이 한글일 때만("쿠폰만 따로" O, "3만 적용" X), "전용"은 끝·띄어쓰기·조사가 올 때만("임직원 전용 쿠폰"·"전용으로" O, "전용계좌" X)
CONDITION_RE: Pattern = re.compile(r"에만|(?<=[가-힣])만\s*(따로|해당|적용|별도)|때만|경우에만|전용(?=$|[\s.,?!]|으로|은|는|이|에|의)")


def looks_like_navigation_query(query: str, pattern: Pattern = NAV_SIGNAL_RE) -> bool:
    return bool(pattern.search(query))


def looks_like_condition_query(query: str, pattern: Pattern = CONDITION_RE) -> bool:
    return bool(pattern.search(query))
